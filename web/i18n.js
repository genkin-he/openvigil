function detect() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage unavailable: use the default */ }
  return "zh"; // Chinese unless the owner switched to English
}

export const lang = detect();

/** t looks up a phrase and fills {name} placeholders; unknown keys show as the key so gaps are visible. */
export function t(key, params = {}) {
  const phrase = DICT[lang][key] ?? DICT.zh[key] ?? key;
  return phrase.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Switch language; the page reloads so every view re-renders in it. */
export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  try { localStorage.setItem(STORE_KEY, next); } catch { /* ignore: the switch just won't persist */ }
  location.reload();
}

/** Fill static markup: data-i18n sets text, data-i18n-<attr> sets that attribute. */
export function applyStatic(root = document) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  for (const el of root.querySelectorAll("*")) {
    for (const { name, value } of [...el.attributes]) {
      if (name === "data-i18n") el.textContent = t(value);
      else if (name.startsWith("data-i18n-")) el.setAttribute(name.slice(10), t(value));
    }
  }
}

